export const DRUGS: Drug[] = RAW_DRUGS.map((d) => ({
  ...d,
  bindings: d.bindings.map(normalizeBinding),
}));

export const DRUG_MAP = Object.fromEntries(DRUGS.map((d) => [d.id, d])) as Record<
  string,
  Drug
>;

export const DRUG_CATEGORIES = [
  ...new Set(DRUGS.map((d) => d.category)),
].sort();

export function searchDrugs(query: string): Drug[] {
  const q = query.trim().toLowerCase();
  if (!q) return DRUGS;
  return DRUGS.filter((d) => {
    if (d.name.toLowerCase().includes(q)) return true;
    if (d.class.toLowerCase().includes(q)) return true;
    if (d.category.toLowerCase().includes(q)) return true;
    if (d.aliases.some((a) => a.toLowerCase().includes(q))) return true;
    if (d.bindings.some((b) => b.receptorId.includes(q))) return true;
    if (d.bindings.some((b) => b.metric.toLowerCase().includes(q))) return true;
    return false;
  });
}

export interface PresetItem {
  drugId: string;
  /** Optional dose override (mg/U). Defaults to drug.defaultDoseMg. */
  doseMg?: number;
}

export interface PresetCocktail {
  id: string;
  name: string;
  /** Specific named drugs, e.g. "Sertraline 50 mg + Bupropion 150 mg". */
  drugsLabel: string;
  description: string;
  /** What the user should notice after loading. */
  highlight: string;
  tag: "risk" | "reversal" | "common" | "compare" | "cardiovascular" | "cns";
  items: PresetItem[];
  /** Convenience list of ids (derived from items). */
  drugIds: string[];
}

function preset(
  p: Omit<PresetCocktail, "drugIds"> & { items: PresetItem[] },
): PresetCocktail {
  return { ...p, drugIds: p.items.map((i) => i.drugId) };
}

