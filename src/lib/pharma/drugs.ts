/** Resolve preset items to SelectedDrug-compatible objects. */
export function presetToSelection(
  p: PresetCocktail,
): { drugId: string; doseMg: number }[] {
  return p.items
    .map((item) => {
      const drug = DRUG_MAP[item.drugId];
      if (!drug) return null;
      return {
        drugId: item.drugId,
        doseMg: item.doseMg ?? drug.defaultDoseMg,
      };
    })
    .filter((x): x is { drugId: string; doseMg: number } => x !== null);
}
